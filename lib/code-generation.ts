export async function parseGeneratedCode(response: string): Promise<{
  title: string
  description: string
  files: Record<string, string>
}> {
  try {
    // Try to extract JSON from the response
    const jsonMatch = response.match(/\{[\s\S]*\}/)
    if (!jsonMatch) {
      throw new Error("No JSON found in response")
    }

    const parsed = JSON.parse(jsonMatch[0])

    if (!parsed.title || !parsed.description || !parsed.files) {
      throw new Error("Invalid response format")
    }

    return {
      title: parsed.title,
      description: parsed.description,
      files: parsed.files,
    }
  } catch (error) {
    console.error("Failed to parse generated code:", error)

    // Fallback: create a simple structure
    return {
      title: "Generated Project",
      description: "Code generated from prompt",
      files: {
        "README.md": "# Generated Project\n\nThis project was generated by Promptmetheus.\n\n" + response,
      },
    }
  }
}

export async function saveGeneratedCode(
  userId: string,
  title: string,
  description: string,
  framework: string,
  files: Record<string, string>,
): Promise<string> {
  const generatedCode = await prisma.generatedCode.create({
    data: {
      userId,
      title,
      description,
      framework,
      code: JSON.stringify(files),
    },
  })

  return generatedCode.id
}

export async function createZipFile(files: Record<string, string>): Promise<Buffer> {
  const zip = new JSZip()

  // Add all files to the zip
  Object.entries(files).forEach(([filename, content]) => {
    zip.file(filename, content)
  })

  // Generate the zip file
  return await zip.generateAsync({ type: "nodebuffer" })
}

export async function getGeneratedProjects(userId: string): Promise<GeneratedProject[]> {
  const projects = await prisma.generatedCode.findMany({
    where: { userId },
    orderBy: { createdAt: "desc" },
  })

  return projects.map((project) => ({
    id: project.id,
    title: project.title,
    description: project.description || "",
    framework: project.framework,
    files: JSON.parse(project.code),
    createdAt: project.createdAt,
  }))
}
