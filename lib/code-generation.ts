import { generateResponse } from "@/lib/llm/server-providers"
import { prisma } from "@/lib/db"
import JSZip from "jszip"

export interface GeneratedProject {
  id: string
  title: string
  description: string
  framework: string
  files: Record<string, string>
  createdAt: Date
}

export const SUPPORTED_FRAMEWORKS = [
  { value: "nextjs", label: "Next.js", description: "Full-stack React framework" },
  { value: "react", label: "React", description: "React single-page application" },
  { value: "html", label: "HTML/CSS/JS", description: "Static HTML website" },
]

export async function generateCode(
  userId: string,
  prompt: string,
  framework = "nextjs",
  provider = "openai",
  model = "gpt-4",
): Promise<{ content: string; tokens: number }> {
  const systemPrompt = getSystemPrompt(framework)

  const messages = [
    { role: "system", content: systemPrompt },
    { role: "user", content: prompt },
  ]

  return await generateResponse(userId, provider, model, messages)
}

